export function SourceLink({ row, children }: { row: MatrixRow; children: ReactNode }) {
  return <a data-source-matrix-row={row} href={approvedUrls[row]} target="_blank" rel="noopener noreferrer" className="underline underline-offset-2">{children}</a>;
}

export function NumberedSource({ number, text }: { number: number; text: string }) {
  const documents = compoundFootnotes[number];
  if (documents) {
    const matches = Object.keys(documents);
    const parts = text.split(new RegExp(`(${matches.join("|")})`, "g"));
    return <>{parts.map((part, index) => documents[part]
      ? <SourceLink key={index} row={documents[part]}>{part}</SourceLink>
      : part)}</>;
  }
  const row = footnoteRows[number];
  return row ? <SourceLink row={row}>{text}</SourceLink> : text;
}
